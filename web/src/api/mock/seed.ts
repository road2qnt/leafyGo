function summary(rows: ApprovalRow[]): ApprovalSummary {
  const approved = rows.filter((row) => row.decision === "approved").length;
  const rejected = rows.filter((row) => row.decision === "rejected").length;
  return { required: rows.length, approved, rejected, pending: rows.length - approved - rejected };
}

function approval(
  proposalId: string,
  groupId: string,
  decision: "approved" | "rejected" | null,
  decidedMinutesAgo?: number,
  comment = "",
): ApprovalRow {
  const group = groups.find((entry) => entry.id === groupId)!;
  const leader = users.find((entry) => entry.id === group.leader_id)!;
  const access = group.access.find((entry) => entry.db_id === proposalDb(proposalId)) ?? group.access[0];
  return {
    group_id: group.id,
    group_name: group.name,
    leader_id: leader.id,
    leader_username: leader.username,
    access_level: access?.level ?? "view",
    decision,
    comment,
    decided_at: decision ? minutesAgo(decidedMinutesAgo ?? 10) : null,
  };
}

