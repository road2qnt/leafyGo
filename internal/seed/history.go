// Hanya untuk koneksi yang belum punya riwayat maupun draft.
func (r *runner) seedHistory(ctx context.Context, p platformResult) error {
	st := r.deps.Store
	for _, name := range []string{"Storefront", "Inventory", "Billing", "People", "Analytics"} {
		conn, ok := p.conns[strings.ToLower(name)]
		if !ok {
			continue
		}
		history, err := st.ListMigrationHistory(ctx, conn.ID, 1)
		if err != nil {
			return err
		}
		drafts, err := st.ListMigrationDrafts(ctx, conn.ID)
		if err != nil {
			return err
		}
		if len(history) > 0 || len(drafts) > 0 {
			continue
		}
		for _, m := range historySeeds[name] {
			if err := r.runMigration(ctx, p, conn, m); err != nil {
				return fmt.Errorf("%s: %s: %w", name, m.Title, err)
			}
		}
	}
	return nil
}

func (r *runner) runMigration(ctx context.Context, p platformResult, conn domain.DBConnection, m migrationSeed) error {
	st := r.deps.Store
	actor, err := p.user(m.Actor)
	if err != nil {
		return err
	}
	at := r.now.AddDate(0, 0, -m.DaysAgo).Add(time.Duration(9+m.DaysAgo%8)*time.Hour + time.Duration(m.DaysAgo*7%60)*time.Minute)

	draft, err := st.CreateMigrationDraft(ctx, domain.MigrationDraft{
		DBID: conn.ID, Title: m.Title, SQLText: m.SQL, CreatedBy: &actor.ID, UpdatedBy: &actor.ID,
	})
	if err != nil {
		return err
	}

	if m.Pending {
		if m.Editor != "" {
			editor, err := p.user(m.Editor)
			if err != nil {
				return err
			}
			if draft, err = st.UpdateMigrationDraft(ctx, conn.ID, draft.ID, m.Title, m.SQL, draft.Revision, editor.ID); err != nil {
				return err
			}
		}
		_, err := st.Pool().Exec(ctx, `
			update migration_drafts set created_at=$2, updated_at=$3 where id=$1`,
			draft.ID, at, at.Add(26*time.Hour))
		return err
	}

	level, err := st.EffectiveLevel(ctx, actor.ID, conn.ID)
	if err != nil {
		return err
	}
	h, err := r.deps.Migrations.ExecuteDraft(ctx, migration.ExecuteInput{
		Actor: actor, DB: conn, Level: level, DraftID: draft.ID, Token: draft.Revision, Title: m.Title, SQL: m.SQL,
	})
	switch {
	case err == nil:
		r.log.Info("executed migration", "db", conn.Name, "version", h.Version, "title", m.Title)
	case errors.Is(err, migration.ErrTarget):
		r.log.Info("migration failed as intended", "db", conn.Name, "version", h.Version, "error", h.Error)
	default:
		return err
	}

	// Sebar waktu eksekusi ke belakang agar riwayat terlihat wajar.
	_, err = st.Pool().Exec(ctx, `
		update migration_history
		set started_at=$2::timestamptz, finished_at=$2::timestamptz + make_interval(secs => coalesce(duration_ms, 0) / 1000.0)
		where id=$1`, h.ID, at)
	if err != nil {
		return err
	}
	_, err = st.Pool().Exec(ctx, `update migration_drafts set created_at=$2, updated_at=$2 where id=$1`, draft.ID, at.Add(-3*time.Hour))
	return err
}
