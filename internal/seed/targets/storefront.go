package targets

import (
	"context"

	"github.com/jackc/pgx/v5"

	"leafygo/internal/seed/dataset"
)

func buildStorefront(ctx context.Context, conn *pgx.Conn, d *dataset.Dataset) error {
	if err := execAll(ctx, conn, `
		create table categories (
			id integer generated by default as identity primary key,
			name text not null,
			slug text not null unique,
			description text not null default ''
		)`, `
		create table products (
			id integer generated by default as identity primary key,
			sku text not null unique,
			name text not null,
			category_id integer not null references categories(id),
			price numeric(10,2) not null check (price >= 0),
			cost numeric(10,2) not null check (cost >= 0),
			weight_grams integer not null check (weight_grams > 0),
			is_active boolean not null default true,
			description text,
			created_at timestamptz not null default now()
		)`, `
		create index products_category_idx on products (category_id)`, `
		create table customers (
			id integer generated by default as identity primary key,
			first_name text not null,
			last_name text not null,
			email text not null,
			phone text,
			marketing_opt_in boolean not null default false,
			created_at timestamptz not null default now()
		)`, `
		create unique index customers_email_lower_idx on customers (lower(email))`, `
		create table addresses (
			id integer generated by default as identity primary key,
			customer_id integer not null references customers(id) on delete cascade,
			label text not null,
			line1 text not null,
			city text not null,
			state char(2) not null,
			postal_code text not null,
			country char(2) not null default 'US',
			is_default boolean not null default false
		)`, `
		create unique index addresses_one_default_idx on addresses (customer_id) where is_default`, `
		create table orders (
			id integer generated by default as identity primary key,
			customer_id integer not null references customers(id),
			shipping_address_id integer references addresses(id) on delete set null,
			status text not null check (status in ('pending', 'paid', 'shipped', 'delivered', 'cancelled', 'refunded')),
			placed_at timestamptz not null,
			subtotal numeric(12,2) not null,
			shipping_fee numeric(10,2) not null default 0,
			tax numeric(10,2) not null default 0,
			total numeric(12,2) not null,
			check (total = subtotal + shipping_fee + tax)
		)`, `
		create index orders_customer_idx on orders (customer_id)`, `
		create table order_items (
			order_id integer not null references orders(id) on delete cascade,
			product_id integer not null references products(id),
			quantity integer not null check (quantity > 0),
			unit_price numeric(10,2) not null check (unit_price >= 0),
			primary key (order_id, product_id)
		)`, `
		create table reviews (
			id integer generated by default as identity primary key,
			product_id integer not null references products(id) on delete cascade,
			customer_id integer not null references customers(id) on delete cascade,
			rating smallint not null check (rating between 1 and 5),
			title text not null,
			body text not null,
			created_at timestamptz not null,
			unique (product_id, customer_id)
		)`, `
		create index reviews_product_idx on reviews (product_id)`, `
		create view order_totals as
		select o.id as order_id,
		       c.first_name || ' ' || c.last_name as customer,
		       o.status,
		       count(i.product_id) as item_count,
		       o.total
		from orders o
		join customers c on c.id = o.customer_id
		left join order_items i on i.order_id = o.id
		group by o.id, c.first_name, c.last_name`,
	); err != nil {
		return err
	}

	var rows [][]any
	for _, c := range d.Categories {
		rows = append(rows, []any{c.ID, c.Name, c.Slug, c.Description})
	}
	if err := copyRows(ctx, conn, []string{"categories"}, []string{"id", "name", "slug", "description"}, rows); err != nil {
		return err
	}

	rows = nil
	for _, p := range d.Products {
		rows = append(rows, []any{p.ID, p.SKU, p.Name, p.CategoryID, dataset.Cents(p.PriceCents), dataset.Cents(p.CostCents), p.WeightGrams, p.IsActive, p.Description, p.CreatedAt})
	}
	if err := copyRows(ctx, conn, []string{"products"},
		[]string{"id", "sku", "name", "category_id", "price", "cost", "weight_grams", "is_active", "description", "created_at"}, rows); err != nil {
		return err
	}

	rows = nil
	for _, c := range d.Customers {
		rows = append(rows, []any{c.ID, c.FirstName, c.LastName, c.Email, c.Phone, c.OptIn, c.CreatedAt})
	}
	if err := copyRows(ctx, conn, []string{"customers"},
		[]string{"id", "first_name", "last_name", "email", "phone", "marketing_opt_in", "created_at"}, rows); err != nil {
		return err
	}

	rows = nil
	for _, a := range d.Addresses {
		rows = append(rows, []any{a.ID, a.CustomerID, a.Label, a.Line1, a.City, a.State, a.PostalCode, a.IsDefault})
	}
	if err := copyRows(ctx, conn, []string{"addresses"},
		[]string{"id", "customer_id", "label", "line1", "city", "state", "postal_code", "is_default"}, rows); err != nil {
		return err
	}

	rows = nil
	var items [][]any
	for _, o := range d.Orders {
		rows = append(rows, []any{o.ID, o.CustomerID, o.AddressID, o.Status, o.PlacedAt,
			dataset.Cents(o.SubtotalCents), dataset.Cents(o.ShippingCents), dataset.Cents(o.TaxCents), dataset.Cents(o.TotalCents)})
		for _, it := range o.Items {
			items = append(items, []any{o.ID, it.ProductID, it.Quantity, dataset.Cents(it.UnitPriceCents)})
		}
	}
	if err := copyRows(ctx, conn, []string{"orders"},
		[]string{"id", "customer_id", "shipping_address_id", "status", "placed_at", "subtotal", "shipping_fee", "tax", "total"}, rows); err != nil {
		return err
	}
	if err := copyRows(ctx, conn, []string{"order_items"}, []string{"order_id", "product_id", "quantity", "unit_price"}, items); err != nil {
		return err
	}

	rows = nil
	for _, r := range d.Reviews {
		rows = append(rows, []any{r.ID, r.ProductID, r.CustomerID, r.Rating, r.Title, r.Body, r.CreatedAt})
	}
	if err := copyRows(ctx, conn, []string{"reviews"},
		[]string{"id", "product_id", "customer_id", "rating", "title", "body", "created_at"}, rows); err != nil {
		return err
	}

	if err := resetSequences(ctx, conn, "categories", "products", "customers", "addresses", "orders", "reviews"); err != nil {
		return err
	}
	_, err := conn.Exec(ctx, "analyze")
	return err
}
