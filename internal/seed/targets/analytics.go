package targets

import (
	"context"
	"sort"
	"time"

	"github.com/brianvoe/gofakeit/v7"
	"github.com/jackc/pgx/v5"

	"leafygo/internal/seed/dataset"
)

type dailySales struct {
	orders, units           int
	grossCents, refundCents int
}

type productMonth struct {
	productID int
	month     time.Time
}

func buildAnalytics(f *gofakeit.Faker) func(context.Context, *pgx.Conn, *dataset.Dataset) error {
	return func(ctx context.Context, conn *pgx.Conn, d *dataset.Dataset) error {
		if err := execAll(ctx, conn, `
			create schema analytics`, `
			create table analytics.daily_sales (
				day date primary key,
				orders integer not null,
				units integer not null,
				gross_revenue numeric(12,2) not null,
				refunds numeric(12,2) not null default 0,
				net_revenue numeric(12,2) generated always as (gross_revenue - refunds) stored
			)`, `
			create table analytics.product_metrics (
				product_id integer not null,
				month date not null,
				units_sold integer not null,
				revenue numeric(12,2) not null,
				avg_rating numeric(3,2),
				primary key (product_id, month)
			)`, `
			create materialized view analytics.monthly_revenue as
			select date_trunc('month', day)::date as month,
			       sum(orders) as orders,
			       sum(gross_revenue) as gross_revenue,
			       sum(net_revenue) as net_revenue
			from analytics.daily_sales
			group by 1
			with no data`, `
			create table etl_runs (
				id integer generated by default as identity primary key,
				job text not null,
				started_at timestamptz not null,
				finished_at timestamptz,
				status text not null check (status in ('running', 'succeeded', 'failed')),
				rows_loaded integer,
				error text
			)`, `
			create table dashboards (
				id integer generated by default as identity primary key,
				name text not null unique,
				owner text not null,
				description text not null,
				created_at timestamptz not null
			)`,
		); err != nil {
			return err
		}

		today := d.Now.Truncate(24 * time.Hour)
		days := map[time.Time]*dailySales{}
		units := map[productMonth]int{}
		revenue := map[productMonth]int{}
		for _, o := range d.Orders {
			day := o.PlacedAt.Truncate(24 * time.Hour)
			if !day.Before(today) || o.Status == "pending" || o.Status == "cancelled" {
				continue
			}
			s := days[day]
			if s == nil {
				s = &dailySales{}
				days[day] = s
			}
			s.orders++
			s.grossCents += o.TotalCents
			if o.Status == "refunded" {
				s.refundCents += o.TotalCents
			}
			month := time.Date(day.Year(), day.Month(), 1, 0, 0, 0, 0, time.UTC)
			for _, it := range o.Items {
				s.units += it.Quantity
				k := productMonth{it.ProductID, month}
				units[k] += it.Quantity
				revenue[k] += it.Quantity * it.UnitPriceCents
			}
		}
		var keys []time.Time
		for day := range days {
			keys = append(keys, day)
		}
		sort.Slice(keys, func(i, j int) bool { return keys[i].Before(keys[j]) })
		var rows [][]any
		for _, day := range keys {
			s := days[day]
			rows = append(rows, []any{day, s.orders, s.units, dataset.Cents(s.grossCents), dataset.Cents(s.refundCents)})
		}
		if err := copyRows(ctx, conn, []string{"analytics", "daily_sales"}, []string{"day", "orders", "units", "gross_revenue", "refunds"}, rows); err != nil {
			return err
		}

		ratings := map[productMonth][2]int{}
		for _, r := range d.Reviews {
			k := productMonth{r.ProductID, time.Date(r.CreatedAt.Year(), r.CreatedAt.Month(), 1, 0, 0, 0, 0, time.UTC)}
			v := ratings[k]
			ratings[k] = [2]int{v[0] + r.Rating, v[1] + 1}
		}
		var metrics []productMonth
		for k := range units {
			metrics = append(metrics, k)
		}
		sort.Slice(metrics, func(i, j int) bool {
			if metrics[i].productID != metrics[j].productID {
				return metrics[i].productID < metrics[j].productID
			}
			return metrics[i].month.Before(metrics[j].month)
		})
		rows = nil
		for _, k := range metrics {
			var avg *float64
			if r := ratings[k]; r[1] > 0 {
				avg = dataset.Ptr(float64(r[0]) / float64(r[1]))
			}
			rows = append(rows, []any{k.productID, k.month, units[k], dataset.Cents(revenue[k]), avg})
		}
		if err := copyRows(ctx, conn, []string{"analytics", "product_metrics"}, []string{"product_id", "month", "units_sold", "revenue", "avg_rating"}, rows); err != nil {
			return err
		}

		rows = nil
		for i := 60; i >= 1; i-- {
			for _, job := range []string{"load_daily_sales", "load_product_metrics"} {
				start := today.AddDate(0, 0, -i).Add(time.Duration(2*60+f.IntRange(0, 20)) * time.Minute)
				status, loaded, errText := "succeeded", any(f.IntRange(20, 900)), any(nil)
				if f.IntRange(1, 100) <= 4 {
					status, loaded = "failed", nil
					errText = dataset.Pick(f, []string{"connection to storefront timed out", "deadlock detected while loading batch", "upstream export file missing"})
				}
				rows = append(rows, []any{len(rows) + 1, job, start, start.Add(time.Duration(f.IntRange(15, 400)) * time.Second), status, loaded, errText})
			}
		}
		if err := copyRows(ctx, conn, []string{"etl_runs"}, []string{"id", "job", "started_at", "finished_at", "status", "rows_loaded", "error"}, rows); err != nil {
			return err
		}

		rows = nil
		for i, db := range []struct{ name, owner, desc string }{
			{"Executive weekly", "putri", "Revenue, orders, and refunds week over week."},
			{"Product performance", "putri", "Units and revenue per product per month."},
			{"Refund watch", "hendra", "Refund rate by day with a 7 day rolling average."},
			{"Category mix", "bayu", "Share of revenue by category."},
			{"ETL health", "bayu", "Job durations and failures over the last 60 days."},
		} {
			rows = append(rows, []any{i + 1, db.name, db.owner, db.desc, today.AddDate(0, -f.IntRange(1, 14), -f.IntRange(0, 27))})
		}
		if err := copyRows(ctx, conn, []string{"dashboards"}, []string{"id", "name", "owner", "description", "created_at"}, rows); err != nil {
			return err
		}

		if err := resetSequences(ctx, conn, "etl_runs", "dashboards"); err != nil {
			return err
		}
		_, err := conn.Exec(ctx, "analyze")
		return err
	}
}
