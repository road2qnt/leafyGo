package targets

import (
	"context"
	"fmt"
	"strings"
	"time"

	"github.com/brianvoe/gofakeit/v7"
	"github.com/jackc/pgx/v5"

	"leafygo/internal/seed/dataset"
)

var warehouseSeeds = []struct{ code, name, city, state string }{
	{"RNO1", "Reno Fulfillment Center", "Reno", "NV"},
	{"CMH1", "Columbus Fulfillment Center", "Columbus", "OH"},
	{"ATL1", "Atlanta Cross-Dock", "Atlanta", "GA"},
	{"PDX1", "Portland Returns Hub", "Portland", "OR"},
}

func buildInventory(f *gofakeit.Faker) func(context.Context, *pgx.Conn, *dataset.Dataset) error {
	return func(ctx context.Context, conn *pgx.Conn, d *dataset.Dataset) error {
		if err := execAll(ctx, conn, `
			create table warehouses (
				id integer generated by default as identity primary key,
				code text not null unique,
				name text not null,
				city text not null,
				state char(2) not null,
				opened_on date not null
			)`, `
			create table suppliers (
				id integer generated by default as identity primary key,
				name text not null unique,
				contact_name text not null,
				email text not null,
				phone text not null,
				country char(2) not null default 'US'
			)`, `
			create table items (
				product_id integer primary key,
				sku text not null unique,
				name text not null,
				supplier_id integer not null references suppliers(id),
				reorder_point integer not null default 20 check (reorder_point >= 0)
			)`, `
			create table stock_levels (
				warehouse_id integer not null references warehouses(id),
				product_id integer not null references items(product_id),
				on_hand integer not null check (on_hand >= 0),
				reserved integer not null default 0 check (reserved >= 0),
				updated_at timestamptz not null,
				primary key (warehouse_id, product_id),
				check (reserved <= on_hand)
			)`, `
			create table purchase_orders (
				id integer generated by default as identity primary key,
				supplier_id integer not null references suppliers(id),
				warehouse_id integer not null references warehouses(id),
				status text not null check (status in ('draft', 'ordered', 'received', 'cancelled')),
				ordered_at timestamptz,
				expected_on date,
				received_at timestamptz
			)`, `
			create table purchase_order_lines (
				purchase_order_id integer not null references purchase_orders(id) on delete cascade,
				line_no smallint not null,
				product_id integer not null references items(product_id),
				quantity integer not null check (quantity > 0),
				unit_cost numeric(10,2) not null,
				primary key (purchase_order_id, line_no)
			)`, `
			create table stock_movements (
				moved_at timestamptz not null,
				warehouse_id integer not null references warehouses(id),
				product_id integer not null references items(product_id),
				quantity integer not null check (quantity <> 0),
				reason text not null check (reason in ('sale', 'restock', 'adjustment', 'return', 'transfer')),
				reference text
			)`,
		); err != nil {
			return err
		}

		var rows [][]any
		for i, w := range warehouseSeeds {
			rows = append(rows, []any{i + 1, w.code, w.name, w.city, w.state, d.Now.AddDate(-f.IntRange(2, 8), -f.IntRange(0, 11), 0)})
		}
		if err := copyRows(ctx, conn, []string{"warehouses"}, []string{"id", "code", "name", "city", "state", "opened_on"}, rows); err != nil {
			return err
		}

		rows = nil
		suppliers := map[string]bool{}
		for i := 1; i <= 30; i++ {
			name := f.Company()
			for suppliers[name] {
				name = f.Company()
			}
			suppliers[name] = true
			first, last := dataset.IndoName(f)
			domain := strings.ToLower(strings.NewReplacer(" ", "", ",", "", ".", "", "&", "and", "'", "").Replace(name)) + ".com"
			rows = append(rows, []any{i, name, first + " " + last, strings.ToLower(first) + "@" + domain, f.PhoneFormatted(), dataset.Pick(f, []string{"US", "US", "US", "CA", "MX", "VN", "PT"})})
		}
		if err := copyRows(ctx, conn, []string{"suppliers"}, []string{"id", "name", "contact_name", "email", "phone", "country"}, rows); err != nil {
			return err
		}

		rows = nil
		var levels [][]any
		for _, p := range d.Products {
			rows = append(rows, []any{p.ID, p.SKU, p.Name, f.IntRange(1, 30), dataset.Pick(f, []int{10, 15, 20, 25, 40})})
			for w := 1; w <= len(warehouseSeeds); w++ {
				if w == 4 && f.IntRange(1, 100) > 30 {
					continue
				}
				onHand := f.IntRange(0, 420)
				if f.IntRange(1, 100) <= 7 {
					onHand = 0
				}
				levels = append(levels, []any{w, p.ID, onHand, f.IntRange(0, min(onHand, 12)), d.Now.Add(-time.Duration(f.IntRange(1, 72)) * time.Hour)})
			}
		}
		if err := copyRows(ctx, conn, []string{"items"}, []string{"product_id", "sku", "name", "supplier_id", "reorder_point"}, rows); err != nil {
			return err
		}
		if err := copyRows(ctx, conn, []string{"stock_levels"}, []string{"warehouse_id", "product_id", "on_hand", "reserved", "updated_at"}, levels); err != nil {
			return err
		}

		rows = nil
		var lines, moves [][]any
		for i := 1; i <= 180; i++ {
			wh := f.IntRange(1, 3)
			ordered := d.Now.Add(-time.Duration(dataset.Skewed(f, 1.2) * float64(380*24*time.Hour))).Truncate(time.Second)
			expected := ordered.AddDate(0, 0, f.IntRange(5, 21))
			status := "received"
			var orderedAt, receivedAt *time.Time
			switch {
			case i > 172:
				status = "draft"
			case f.IntRange(1, 100) <= 5:
				status = "cancelled"
				orderedAt = &ordered
			case expected.After(d.Now):
				status = "ordered"
				orderedAt = &ordered
			default:
				orderedAt = &ordered
				receivedAt = dataset.Ptr(expected.Add(time.Duration(f.IntRange(-48, 72)) * time.Hour))
			}
			rows = append(rows, []any{i, f.IntRange(1, 30), wh, status, orderedAt, expected, receivedAt})
			lineCount := f.IntRange(1, 6)
			for n := 1; n <= lineCount; n++ {
				p := dataset.Pick(f, d.Products)
				qty := dataset.Pick(f, []int{24, 48, 50, 100, 120, 200})
				lines = append(lines, []any{i, n, p.ID, qty, dataset.Cents(p.CostCents)})
				if receivedAt != nil {
					moves = append(moves, []any{*receivedAt, wh, p.ID, qty, "restock", fmt.Sprintf("PO-%05d", i)})
				}
			}
		}
		if err := copyRows(ctx, conn, []string{"purchase_orders"},
			[]string{"id", "supplier_id", "warehouse_id", "status", "ordered_at", "expected_on", "received_at"}, rows); err != nil {
			return err
		}
		if err := copyRows(ctx, conn, []string{"purchase_order_lines"},
			[]string{"purchase_order_id", "line_no", "product_id", "quantity", "unit_cost"}, lines); err != nil {
			return err
		}

		for _, o := range d.Orders {
			if o.Status == "pending" || o.Status == "cancelled" {
				continue
			}
			wh := f.IntRange(1, 3)
			at := o.PlacedAt.Add(time.Duration(f.IntRange(2, 30)) * time.Hour)
			for _, it := range o.Items {
				moves = append(moves, []any{at, wh, it.ProductID, -it.Quantity, "sale", fmt.Sprintf("order #%d", o.ID)})
				if o.Status == "refunded" {
					moves = append(moves, []any{at.AddDate(0, 0, f.IntRange(6, 20)), 4, it.ProductID, it.Quantity, "return", fmt.Sprintf("order #%d", o.ID)})
				}
			}
		}
		for i := 0; i < 160; i++ {
			p := dataset.Pick(f, d.Products)
			qty := f.IntRange(-6, 4)
			if qty == 0 {
				qty = -1
			}
			moves = append(moves, []any{d.Now.Add(-time.Duration(f.IntRange(1, 360*24)) * time.Hour), f.IntRange(1, 3), p.ID, qty, "adjustment",
				dataset.Pick(f, []string{"cycle count", "damaged in handling", "found during audit", "mislabeled bin"})})
		}
		for i := 0; i < 40; i++ {
			p := dataset.Pick(f, d.Products)
			at := d.Now.Add(-time.Duration(f.IntRange(1, 300*24)) * time.Hour)
			qty := f.IntRange(10, 60)
			ref := fmt.Sprintf("TR-%04d", 1000+i)
			moves = append(moves, []any{at, 1, p.ID, -qty, "transfer", ref}, []any{at.Add(36 * time.Hour), 2, p.ID, qty, "transfer", ref})
		}
		if err := copyRows(ctx, conn, []string{"stock_movements"},
			[]string{"moved_at", "warehouse_id", "product_id", "quantity", "reason", "reference"}, moves); err != nil {
			return err
		}

		if err := resetSequences(ctx, conn, "warehouses", "suppliers", "purchase_orders"); err != nil {
			return err
		}
		_, err := conn.Exec(ctx, "analyze")
		return err
	}
}
